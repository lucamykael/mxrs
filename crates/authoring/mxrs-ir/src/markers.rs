/// A typed reference to an entity, carrying no runtime state beyond what's
/// needed to resolve back to the qualified name `mxrs-writer` already
/// expects (`"Module.Entity"`) — so once `mxrs-dsl` is wired to accept
/// `Ref<M>` in place of a raw target string, existing target-resolution
/// code in `mxrs-writer::domain` (which already branches on a `.` in the
/// string) needs no changes at all.
#[derive(Debug)]
pub struct Ref<M: EntityMarker>(PhantomData<M>);

impl<M: EntityMarker> Ref<M> {
    pub fn new() -> Self {
        Ref(PhantomData)
    }

    pub fn qualified_name(&self) -> String {
        M::qualified_name()
    }
}

impl<M: EntityMarker> Default for Ref<M> {
    fn default() -> Self {
        Self::new()
    }
}

impl<M: EntityMarker> Clone for Ref<M> {
    fn clone(&self) -> Self {
        *self
    }
}

impl<M: EntityMarker> Copy for Ref<M> {}

/// A value-level handle to one attribute of one entity.
///
/// `#[mxrs::entity]` gives every field an accessor returning one of these
/// (`Order::number()`), so authored code names an attribute through the
/// entity it belongs to instead of through a separately generated marker
/// type. The handle is zero-sized: everything it knows lives in `A`.
#[derive(Debug)]
pub struct AttributeRef<A: AttributeMarker>(PhantomData<A>);

impl<A: AttributeMarker> AttributeRef<A> {
    pub const fn new() -> Self {
        AttributeRef(PhantomData)
    }

    /// The attribute's Mendix name, exactly as the model stores it.
    pub fn name(&self) -> &'static str {
        A::NAME
    }

    /// `Module.Entity.Attribute`.
    pub fn qualified_name(&self) -> String {
        format!("{}.{}", A::Entity::qualified_name(), A::NAME)
    }
}

impl<A: AttributeMarker> Default for AttributeRef<A> {
    fn default() -> Self {
        Self::new()
    }
}

impl<A: AttributeMarker> Clone for AttributeRef<A> {
    fn clone(&self) -> Self {
        *self
    }
}

impl<A: AttributeMarker> Copy for AttributeRef<A> {}

/// A value-level handle to one association, the counterpart of
/// [`AttributeRef`] for `Reference<T>`/`ReferenceSet<T>` fields.
#[derive(Debug)]
pub struct AssociationRef<A: AssociationMarker>(PhantomData<A>);

impl<A: AssociationMarker> AssociationRef<A> {
    pub const fn new() -> Self {
        AssociationRef(PhantomData)
    }

    /// The association's Mendix name, exactly as the model stores it.
    pub fn name(&self) -> &'static str {
        A::NAME
    }

    /// `Module.Association` — the form the native model stores.
    pub fn qualified_name(&self) -> String {
        format!("{}.{}", A::From::MODULE, A::NAME)
    }
}

impl<A: AssociationMarker> Default for AssociationRef<A> {
    fn default() -> Self {
        Self::new()
    }
}

impl<A: AssociationMarker> Clone for AssociationRef<A> {
    fn clone(&self) -> Self {
        *self
    }
}

impl<A: AssociationMarker> Copy for AssociationRef<A> {}

#[cfg(test)]
mod tests {
    use super::*;

    struct Order;
    impl EntityMarker for Order {
        const MODULE: &'static str = "Sales";
        const NAME: &'static str = "Order";
    }

    struct OrderNumber;
    impl AttributeMarker for OrderNumber {
        type Entity = Order;
        const NAME: &'static str = "Number";
    }

    struct Customer;
    impl EntityMarker for Customer {
        const MODULE: &'static str = "Sales";
        const NAME: &'static str = "Customer";
    }

    struct OrderCustomer;
    impl AssociationMarker for OrderCustomer {
        type From = Order;
        type To = Customer;
        const NAME: &'static str = "Order_Customer";
        const ASSOCIATION_TYPE: crate::AssociationType = crate::AssociationType::Reference;
    }

    #[test]
    fn qualified_name_joins_module_and_entity() {
        assert_eq!(Order::qualified_name(), "Sales.Order");
    }

    #[test]
    fn ref_resolves_to_its_marker_qualified_name() {
        let r: Ref<Order> = Ref::new();
        assert_eq!(r.qualified_name(), "Sales.Order");
    }

    #[test]
    fn attribute_marker_names_its_owning_entity() {
        assert_eq!(OrderNumber::NAME, "Number");
        assert_eq!(
            <OrderNumber as AttributeMarker>::Entity::qualified_name(),
            "Sales.Order"
        );
    }

    struct ActNotify;
    impl MicroflowMarker for ActNotify {
        const MODULE: &'static str = "Sales";
        const NAME: &'static str = "ACT_Notify";
    }

    #[test]
    fn microflow_marker_qualified_name_joins_module_and_name() {
        assert_eq!(ActNotify::qualified_name(), "Sales.ACT_Notify");
    }

    #[test]
    fn microflow_ref_resolves_to_its_marker_qualified_name() {
        let r: MicroflowRef<ActNotify> = MicroflowRef::new();
        assert_eq!(r.qualified_name(), "Sales.ACT_Notify");
    }

    struct ActFetchOrder;
    impl NanoflowMarker for ActFetchOrder {
        const MODULE: &'static str = "Sales";
        const NAME: &'static str = "NF_FetchOrder";
    }

    #[test]
    fn nanoflow_marker_qualified_name_joins_module_and_name() {
        assert_eq!(ActFetchOrder::qualified_name(), "Sales.NF_FetchOrder");
    }

    #[test]
    fn nanoflow_ref_resolves_to_its_marker_qualified_name() {
        let r: NanoflowRef<ActFetchOrder> = NanoflowRef::new();
        assert_eq!(r.qualified_name(), "Sales.NF_FetchOrder");
    }

    #[test]
    fn association_marker_names_its_from_to_and_type() {
        assert_eq!(OrderCustomer::NAME, "Order_Customer");
        assert_eq!(
            <OrderCustomer as AssociationMarker>::From::qualified_name(),
            "Sales.Order"
        );
        assert_eq!(
            <OrderCustomer as AssociationMarker>::To::qualified_name(),
            "Sales.Customer"
        );
        assert_eq!(
            OrderCustomer::ASSOCIATION_TYPE,
            crate::AssociationType::Reference
        );
    }
}
